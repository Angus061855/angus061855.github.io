// 把最新 3 篇文章直接寫進 index.html 的 #blog-grid，讓爬蟲與 JS 失敗的使用者也看得到文章卡片。
// 只在 API 回傳正常時改寫；任何錯誤都保留現有內容。
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export const START = '<!-- HOME-POSTS:START (generated by scripts/sync-home-posts.mjs) -->';
export const END = '<!-- HOME-POSTS:END -->';
const API = 'https://as-blog-cache.angus061855.workers.dev/posts';
const FALLBACK_API = 'https://polished-truth-9fc2.angus061855.workers.dev/posts';

const esc = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const clean = (t) => String(t || '').replace(/[，、。]/g, '　').replace(/　{2,}/g, '　').replace(/　([？?！!])/g, '$1').trim();

export function card(p) {
  const cover = p.cover && /^https:\/\//.test(p.cover)
    ? `<img class="blog-card-cover" src="${esc(p.cover)}" alt="${esc(clean(p.title))}" width="720" height="405" loading="lazy" decoding="async"/>`
    : '<div class="blog-card-cover-placeholder"></div>';
  return `        <a class="blog-card" href="/post/${esc(p.slug)}">
          ${cover}
          <div class="blog-card-body">
            <div class="blog-card-meta"><div class="blog-card-date">${esc(p.date)}</div></div>
            <div class="blog-card-title">${esc(clean(p.title))}</div>
            <div class="blog-card-summary">${esc(clean(p.summary))}</div>
          </div>
        </a>`;
}

export function build(posts, n = 3) {
  const ok = posts.filter((p) => p?.slug && p?.title && /^[A-Za-z0-9-]+$/.test(p.slug));
  if (ok.length < n) throw new Error(`只有 ${ok.length} 篇有效文章，保留現有內容`);
  return [START, ...ok.slice(0, n).map(card), END].join('\n');
}

async function getPosts() {
  for (const url of [API, FALLBACK_API]) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(20000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = await res.json();
      if (Array.isArray(data) && data.length) return data;
    } catch (e) { console.warn(`${url} 失敗：${e.message}`); }
  }
  throw new Error('兩個 API 都失敗，保留現有首頁文章');
}

async function main() {
  const path = new URL('../index.html', import.meta.url);
  const html = await readFile(path, 'utf8');
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s === -1 || e < s) throw new Error('index.html 找不到 HOME-POSTS 標記');
  const block = build(await getPosts());
  await writeFile(path, html.slice(0, s) + block + html.slice(e + END.length), 'utf8');
  console.log('index.html 首頁文章卡片已更新');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
