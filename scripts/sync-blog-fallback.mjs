// 把文章清單直接寫進 blog.html 的靜態區塊，讓爬蟲不用執行 JS 也能看到所有文章連結。
// 頁面載入後 blog.html 自己的 JS 仍會用 Worker 資料重畫 #blog-grid，對使用者沒有差異。
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { isRedirectedSlug } from './post-redirects.mjs';

export const START = '<!-- BLOG-FALLBACK:START (generated by scripts/sync-blog-fallback.mjs) -->';
export const END = '<!-- BLOG-FALLBACK:END -->';
// 指南頁放在目錄最前面；被整併進指南（正式站 301）的舊文章不再列出，避免目錄連到轉址網址。
export const GUIDES = [
  { href: '/guides/hotel-pr-guide/', title: '酒店公關是什麼？工作內容、薪水、條件與入行流程' },
  { href: '/guides/hotel-pr-salary/', title: '酒店公關薪水怎麼算？節薪、節數與扣款一次看懂' },
  { href: '/guides/hotel-contract/', title: '酒店公關要簽合約嗎？簽之前要看的 8 個條款' },
  { href: '/guides/choose-agent/', title: '台北酒店經紀推薦前必看：怎麼挑＋10 問檢查清單' },
  { href: '/guides/is-hotel-work-safe/', title: '酒店上班安全嗎？入行前要知道的風險與求助管道' }
];
const isRedirectedHref = (href) => href.startsWith('/post/') && isRedirectedSlug(href.slice('/post/'.length));

export function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

function card({ href, title }) {
  return [
    `    <a class="blog-card" href="${escapeHtml(href)}">`,
    '      <div class="blog-card-body">',
    `        <div class="blog-card-title">${escapeHtml(title)}</div>`,
    '        <div class="blog-card-author">大頭・AS娛樂</div>',
    '      </div>',
    '    </a>'
  ].join('\n');
}

// 既有區塊內、但這次 API 沒回傳的文章連結要保留（API 一次最多回 100 篇，較舊文章仍在線上）。
export function existingCards(block) {
  return [...block.matchAll(/<a class="blog-card" href="(\/post\/[^"]+)">[\s\S]*?<div class="blog-card-title">([\s\S]*?)<\/div>/g)]
    .map(([, href, title]) => ({ href, title: title.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&') }));
}

export function buildBlock(posts, previous = []) {
  const seen = new Set();
  const cards = [...GUIDES];
  for (const p of posts) {
    if (!p?.slug || !p?.title || !/^[A-Za-z0-9-]+$/.test(p.slug)) continue;
    const href = `/post/${p.slug}`;
    if (seen.has(href) || isRedirectedHref(href)) continue;
    seen.add(href); cards.push({ href, title: p.title });
  }
  for (const c of previous) if (!seen.has(c.href) && !isRedirectedHref(c.href)) { seen.add(c.href); cards.push(c); }
  return [START, ...cards.map(card), `    ${END}`].join('\n');
}

export function replaceBlock(html, block) {
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s !== -1 && e > s) return html.slice(0, s) + block + html.slice(e + END.length);
  // 第一次執行：在「載入更多」按鈕後面加一個可展開的完整文章目錄（不動 JS 管理的 #blog-grid，避免版面跳動）
  const anchor = '<button class="blog-load-more" id="blog-load-more" type="button" hidden>載入更多文章</button>';
  const i = html.indexOf(anchor);
  if (i === -1) throw new Error('blog.html 找不到載入更多按鈕');
  const archive = [
    '',
    '  <details class="blog-archive">',
    '    <summary>全部文章目錄</summary>',
    '    <div class="blog-grid blog-archive-grid">',
    '    ' + block,
    '    </div>',
    '  </details>'
  ].join('\n');
  return html.slice(0, i + anchor.length) + archive + html.slice(i + anchor.length);
}

// post-index.json：sitemap 上所有正式文章（不含轉址）的 slug／標題／日期／摘要，
// 給 blog.html 的靜態目錄與前端搜尋、分類、分頁使用（posts API 一次只回最新 100 篇）。
export const INDEX_PATH = new URL('../post-index.json', import.meta.url);
const SITEMAP_PATH = new URL('../sitemap-posts.xml', import.meta.url);
const pick = (p) => ({ slug: p.slug, title: String(p.title || '').trim(), date: String(p.date || '').slice(0, 10), summary: String(p.summary || '').trim() });

export function sitemapSlugs(xml) {
  return [...xml.matchAll(/<loc>https:\/\/as-ent-tw\.com\/post\/([A-Za-z0-9-]+)<\/loc>/g)].map((m) => m[1]).filter((s) => !isRedirectedSlug(s));
}

// 依 sitemap 決定收錄範圍；標題優先用 API 最新資料，其次沿用既有索引，最後才逐篇向 API 查（每篇間隔 400ms）。
export async function buildIndex({ apiPosts, existing, slugs, fetchPost, sleep = (ms) => new Promise((r) => setTimeout(r, ms)) }) {
  const known = new Map(existing.map((p) => [p.slug, p]));
  for (const p of apiPosts) if (p?.slug && p?.title) known.set(p.slug, pick(p));
  const out = [];
  let fetched = 0;
  for (const slug of slugs) {
    let entry = known.get(slug);
    if (!entry?.title) {
      if (fetched++) await sleep(400);
      try { const p = await fetchPost(slug); if (p?.title) entry = pick({ ...p, slug }); } catch {}
    }
    if (entry?.title) out.push(entry);
  }
  return out.sort((a, b) => b.date.localeCompare(a.date) || b.slug.localeCompare(a.slug));
}

async function main() {
  const worker = 'https://polished-truth-9fc2.angus061855.workers.dev';
  const path = new URL('../blog.html', import.meta.url);
  const res = await fetch(`${worker}/posts`, { signal: AbortSignal.timeout(20000) });
  if (!res.ok) throw new Error(`posts API ${res.status}`);
  const posts = await res.json();
  if (!Array.isArray(posts) || posts.length < 20) throw new Error(`posts API 只回傳 ${posts?.length} 篇，保留現有清單`);

  let existing = [];
  try { existing = JSON.parse(await readFile(INDEX_PATH, 'utf8')); } catch {}
  const slugs = sitemapSlugs(await readFile(SITEMAP_PATH, 'utf8'));
  const index = await buildIndex({
    apiPosts: posts, existing, slugs,
    fetchPost: async (slug) => {
      const r = await fetch(`${worker}/posts/${encodeURIComponent(slug)}`, { signal: AbortSignal.timeout(15000) });
      return r.ok ? r.json() : null;
    }
  });
  // 少於既有索引 90% 視為 API 異常，保留舊檔
  if (index.length < Math.max(50, existing.length * 0.9)) throw new Error(`索引只有 ${index.length} 篇（原 ${existing.length}），保留現有內容`);
  await writeFile(INDEX_PATH, JSON.stringify(index, null, 1) + '\n', 'utf8');

  const html = await readFile(path, 'utf8');
  const s = html.indexOf(START), e = html.indexOf(END);
  const previous = s !== -1 && e > s ? existingCards(html.slice(s, e)) : existingCards(html.slice(html.indexOf('id="blog-grid"')).split('blog-load-more')[0]);
  await writeFile(path, replaceBlock(html, buildBlock(index, previous)), 'utf8');
  console.log(`blog.html fallback: ${posts.length} API posts, post-index ${index.length} 篇`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
