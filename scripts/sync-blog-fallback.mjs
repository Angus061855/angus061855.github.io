// 把文章清單直接寫進 blog.html 的靜態區塊，讓爬蟲不用執行 JS 也能看到所有文章連結。
// 頁面載入後 blog.html 自己的 JS 仍會用 Worker 資料重畫 #blog-grid，對使用者沒有差異。
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export const START = '<!-- BLOG-FALLBACK:START (generated by scripts/sync-blog-fallback.mjs) -->';
export const END = '<!-- BLOG-FALLBACK:END -->';
const GUIDE = { href: '/guides/hotel-pr-guide/', title: '酒店公關是什麼？工作內容、薪水、條件與入行流程' };

export function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

function card({ href, title }) {
  return [
    `    <a class="blog-card" href="${escapeHtml(href)}">`,
    '      <div class="blog-card-body">',
    `        <div class="blog-card-title">${escapeHtml(title)}</div>`,
    '        <div class="blog-card-author">大頭・AS娛樂</div>',
    '      </div>',
    '    </a>'
  ].join('\n');
}

// 既有區塊內、但這次 API 沒回傳的文章連結要保留（API 一次最多回 100 篇，較舊文章仍在線上）。
export function existingCards(block) {
  return [...block.matchAll(/<a class="blog-card" href="(\/post\/[^"]+)">[\s\S]*?<div class="blog-card-title">([\s\S]*?)<\/div>/g)]
    .map(([, href, title]) => ({ href, title: title.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&') }));
}

export function buildBlock(posts, previous = []) {
  const seen = new Set();
  const cards = [GUIDE];
  for (const p of posts) {
    if (!p?.slug || !p?.title || !/^[A-Za-z0-9-]+$/.test(p.slug)) continue;
    const href = `/post/${p.slug}`;
    if (seen.has(href)) continue;
    seen.add(href); cards.push({ href, title: p.title });
  }
  for (const c of previous) if (!seen.has(c.href)) { seen.add(c.href); cards.push(c); }
  return [START, ...cards.map(card), `    ${END}`].join('\n');
}

export function replaceBlock(html, block) {
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s !== -1 && e > s) return html.slice(0, s) + block + html.slice(e + END.length);
  // 第一次執行：在「載入更多」按鈕後面加一個可展開的完整文章目錄（不動 JS 管理的 #blog-grid，避免版面跳動）
  const anchor = '<button class="blog-load-more" id="blog-load-more" type="button" hidden>載入更多文章</button>';
  const i = html.indexOf(anchor);
  if (i === -1) throw new Error('blog.html 找不到載入更多按鈕');
  const archive = [
    '',
    '  <details class="blog-archive">',
    '    <summary>全部文章目錄</summary>',
    '    <div class="blog-grid blog-archive-grid">',
    '    ' + block,
    '    </div>',
    '  </details>'
  ].join('\n');
  return html.slice(0, i + anchor.length) + archive + html.slice(i + anchor.length);
}

async function main() {
  const worker = 'https://polished-truth-9fc2.angus061855.workers.dev';
  const path = new URL('../blog.html', import.meta.url);
  const res = await fetch(`${worker}/posts`, { signal: AbortSignal.timeout(20000) });
  if (!res.ok) throw new Error(`posts API ${res.status}`);
  const posts = await res.json();
  if (!Array.isArray(posts) || posts.length < 20) throw new Error(`posts API 只回傳 ${posts?.length} 篇，保留現有清單`);
  const html = await readFile(path, 'utf8');
  const s = html.indexOf(START), e = html.indexOf(END);
  const previous = s !== -1 && e > s ? existingCards(html.slice(s, e)) : existingCards(html.slice(html.indexOf('id="blog-grid"')).split('blog-load-more')[0]);
  await writeFile(path, replaceBlock(html, buildBlock(posts, previous)), 'utf8');
  console.log(`blog.html fallback: ${posts.length} API posts`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
